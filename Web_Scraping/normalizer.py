"""Turns one source's raw detail fields + one LLM extraction result into the
final scheme record schema. This is the single place field-shaping logic
lives — every source module (myscheme now, others later, e.g. a future WCD
Karnataka module) feeds the exact same schema through build_record() instead
of each re-implementing its own record assembly.

Source contract `detail` must satisfy (see sources.py's fetch_myscheme_detail
for the myscheme implementation of this contract):
    scheme_name             str
    benefits_text           str (possibly empty)
    application_process_text str (possibly empty)
    application_link        str (possibly empty)
    documents_text          str (possibly empty)
    scheme_status           str
plus whatever text sections extract.py's prompt reads (brief_description,
detailed_description, eligibility_text) — build_record itself never touches
those directly, only extract.py does.

SCHEMA TRIMMED 2026-09-09: scheme_level, income_limit_rural,
income_limit_urban, source_mismatch, uncertain_fields, field_provenance,
last_verified, source, extraction_method, extraction_model, and
extraction_error were removed from the OUTPUT record — Backend/services/
ruleEngine.js never reads any of them (verified by reading that file
directly), so this pipeline stopped writing them into karnataka_schemes.json.
The pre-trim data, including all of these fields, is preserved in
karnataka_schemes_full.json — that file is the only remaining record of this
diagnostic work and is not regenerated by this pipeline.

ALIAS DUPLICATION REMOVED 2026-09-09: this record used to carry
caste_restriction AND caste_category (same value, two keys), and occupation
AND applicant_type (same value, two keys) — config.BACKEND_COMPAT_ALIASES
used to add the second name of each pair alongside the first. Reading
Backend/services/ruleEngine.js directly confirms evaluateCasteRule reads
ONLY scheme.caste_category and evaluateOccupationRule reads ONLY
scheme.applicant_type — neither rule, nor anything else in that file, ever
reads scheme.caste_restriction or scheme.occupation. So the pipeline's own
name in each pair was write-only dead weight in the final record; only the
backend's name is kept now. extract.py's LLM-facing working dict still uses
"occupation"/"caste_restriction" as its internal key names (see its module
docstring) — that's a deliberate choice to stay compatible with the existing
extraction cache without a migration; this function is the one place those
internal names get renamed for the record actually written to disk.

This does NOT remove the underlying SAFETY BEHAVIOR — build_record() still
nulls benefits/application_process/application_link/documents_required/
scheme_status when extract.py determines the source text doesn't match the
scheme name (still tracked internally via llm_fields["source_mismatch"]).
What changed is only that this fact is no longer written out as its own
field: a mismatched record's nulls are now indistinguishable from a
genuinely-stated-nothing record's nulls in the live file. karnataka_schemes_
full.json is the only place that distinction still exists.
"""

def build_record(detail: dict, source_url: str, llm_fields: dict, source: str, scheme_level: str) -> dict:
    # Still computed and used internally for the nulling logic below — just
    # no longer written out as its own field. See module docstring.
    source_mismatch = llm_fields.get("source_mismatch", False)

    # benefits/application_process/application_link/documents_required/
    # scheme_status are direct passthroughs from the source's own structured
    # API, never LLM-touched — but they come from the exact same per-scheme
    # source record whose PROSE sections extract.py's LLM pass already judged
    # to be about a different scheme. That judgment doesn't stop applying just
    # because a field skips the LLM: a mismatched source's "benefits" text is
    # just as much about the wrong scheme as its "eligibility" text was. Null
    # them too on a mismatch, for the same reason description/eligibility are
    # nulled — a wrong-but-well-formed value is worse than a null.
    benefits = None if source_mismatch else (detail["benefits_text"] or None)
    application_process = None if source_mismatch else (detail["application_process_text"] or None)
    application_link = None if source_mismatch else (detail["application_link"] or None)
    documents_required = None if source_mismatch else (detail["documents_text"] or None)
    scheme_status = None if source_mismatch else detail["scheme_status"]

    record = {
        "scheme_name": detail["scheme_name"],
        "description": llm_fields["description"],
        "eligibility": llm_fields["eligibility"],
        "age_min": llm_fields["age_min"],
        "age_max": llm_fields["age_max"],
        "gender": llm_fields["gender"],
        "income_limit": llm_fields["income_limit"],
        # Renamed from extract.py's internal "caste_restriction"/"occupation"
        # working names to the names Backend/services/ruleEngine.js actually
        # reads (evaluateCasteRule / evaluateOccupationRule) — see module
        # docstring. Written once, under one name; no alias.
        "caste_category": llm_fields["caste_restriction"],
        "applicant_type": llm_fields["occupation"],
        "district": llm_fields["district"],
        "education": llm_fields["education"],
        "special_conditions": llm_fields["special_conditions"],
        "ration_card_type": llm_fields["ration_card_type"],
        "minority_community_required": llm_fields["minority_community_required"],
        "disability_required": llm_fields["disability_required"],
        "benefits": benefits,
        "application_process": application_process,
        "application_link": application_link,
        "documents_required": documents_required,
        "source_url": source_url,
        "scheme_status": scheme_status,
    }
    return record
